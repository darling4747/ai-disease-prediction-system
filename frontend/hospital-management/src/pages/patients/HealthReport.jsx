import React, { useEffect, useState } from 'react';
import {
  Alert,
  Box,
  Button,
  Card,
  CardContent,
  Chip,
  Container,
  Divider,
  Grid,
  Typography,
} from '@mui/material';
import { Description, Print } from '@mui/icons-material';
import { useNavigate, useParams } from 'react-router-dom';
import authService from '../../services/authService';
import predictionService from '../../services/predictionService';
import { getRiskLabel, getRiskLevel } from '../../utils/riskLevel';
import { getDiseaseInfo } from '../../utils/diseaseMap';

const getTopPrediction = (record) => {
  const preds = record?.predictions || [];
  if (!preds.length) return null;
  return [...preds].sort((a, b) => Number(b.probability || 0) - Number(a.probability || 0))[0];
};

const HealthReport = () => {
  const { id } = useParams();
  const navigate = useNavigate();
  const [report, setReport] = useState(null);
  const [loading, setLoading] = useState(true);
  const [error, setError] = useState(null);

  useEffect(() => {
    const load = async () => {
      try {
        if (id) {
          const data = await predictionService.getPredictionById(id);
          setReport(data);
        } else {
          const user = authService.getCurrentUser();
          const history = await predictionService.getPredictionHistory(user?.userId);
          setReport(history?.[0] || null);
        }
      } catch (err) {
        console.error(err);
        setError('Unable to load health report.');
      } finally {
        setLoading(false);
      }
    };
    load();
  }, [id]);

  const handlePrint = () => window.print();

  if (loading) {
    return (
      <Container sx={{ py: 4 }}>
        <Typography>Loading health report...</Typography>
      </Container>
    );
  }

  if (error || !report) {
    return (
      <Container sx={{ py: 4 }}>
        <Alert severity="warning">{error || 'No prediction records found. Run AI Diagnosis first.'}</Alert>
        <Button sx={{ mt: 2 }} variant="contained" onClick={() => navigate('/')}>
          Start AI Diagnosis
        </Button>
      </Container>
    );
  }

  const top = getTopPrediction(report);
  const diseaseName = top?.name || report?.metadata?.agentDecision?.selectedDisease || 'Pending';
  const riskLevel = getRiskLevel(diseaseName);
  const diseaseInfo = getDiseaseInfo(diseaseName);
  const agent = report?.metadata?.agentDecision || {};

  return (
    <Container maxWidth="md" sx={{ py: 4 }} className="health-report-print">
      <Box sx={{ display: 'flex', justifyContent: 'space-between', alignItems: 'center', mb: 3 }}>
        <Box sx={{ display: 'flex', alignItems: 'center', gap: 1.5 }}>
          <Description color="primary" sx={{ fontSize: 36 }} />
          <Box>
            <Typography variant="h4" fontWeight={700}>
              Health Report
            </Typography>
            <Typography color="text.secondary">
              AI prediction summary — {new Date(report.timestamp).toLocaleString()}
            </Typography>
          </Box>
        </Box>
        <Button variant="outlined" startIcon={<Print />} onClick={handlePrint}>
          Print Report
        </Button>
      </Box>

      <Alert severity="info" sx={{ mb: 2 }}>
        This report is generated by the CureAI decision-support system and is not a formal medical record.
      </Alert>

      <Card>
        <CardContent>
          <Typography variant="overline">Patient summary</Typography>
          <Typography variant="h5" gutterBottom>
            {diseaseName}
          </Typography>
          <Chip label={getRiskLabel(riskLevel)} color={riskLevel === 'critical' ? 'error' : 'default'} sx={{ mb: 2 }} />

          <Grid container spacing={2}>
            <Grid item xs={12} sm={6}>
              <Typography variant="subtitle2" color="text.secondary">
                Symptoms analyzed
              </Typography>
              <Typography>
                {(report.symptoms || []).join(', ') || 'Not recorded'}
              </Typography>
            </Grid>
            <Grid item xs={12} sm={6}>
              <Typography variant="subtitle2" color="text.secondary">
                Confidence
              </Typography>
              <Typography>
                {top?.probability
                  ? `${(top.probability * 100).toFixed(1)}%`
                  : agent.confidence || 'N/A'}
              </Typography>
            </Grid>
            <Grid item xs={12} sm={6}>
              <Typography variant="subtitle2" color="text.secondary">
                Doctor recommendation
              </Typography>
              <Typography>
                {top?.doctorSpecialization || agent.doctorRecommendation || 'General Practitioner'}
              </Typography>
            </Grid>
            <Grid item xs={12} sm={6}>
              <Typography variant="subtitle2" color="text.secondary">
                Hospital department
              </Typography>
              <Typography>
                {top?.hospitalDepartment || agent.hospitalSuggestion || 'Outpatient'}
              </Typography>
            </Grid>
          </Grid>

          <Divider sx={{ my: 2 }} />

          <Typography variant="subtitle1" fontWeight={700} gutterBottom>
            Clinical description
          </Typography>
          <Typography paragraph>
            {top?.description || diseaseInfo?.description || 'No description available.'}
          </Typography>

          {diseaseInfo?.medicines?.length > 0 && (
            <>
              <Typography variant="subtitle1" fontWeight={700} gutterBottom>
                Medicine guidance
              </Typography>
              <Typography paragraph>{diseaseInfo.medicines.join(' • ')}</Typography>
            </>
          )}

          {report.metadata?.medicalAdvice && (
            <>
              <Divider sx={{ my: 2 }} />
              <Typography variant="subtitle1" fontWeight={700} gutterBottom>
                Doctor notes
              </Typography>
              <Typography paragraph>{report.metadata.medicalAdvice}</Typography>
              <Typography variant="caption" color="text.secondary">
                Advised by {report.metadata.advisedBy || 'physician'} on{' '}
                {report.metadata.advisedAt || '—'}
              </Typography>
            </>
          )}

          <Divider sx={{ my: 2 }} />
          <Typography variant="caption" color="text.secondary">
            Report ID: {report.id} • Agent: {report.metadata?.agentType || 'Healthcare Assistant'}
          </Typography>
        </CardContent>
      </Card>
    </Container>
  );
};

export default HealthReport;
